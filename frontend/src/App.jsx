function reportHelp(label) {
  if (ROW_HELP[label]) return ROW_HELP[label]
  const lower = label.toLowerCase()
  if (lower.includes('share')) return 'Share counts can change with buybacks, stock-based compensation, and splits. Compare the reported period and company notes.'
  if (lower.includes('debt') || lower.includes('liabilit')) return 'A reported obligation at the end of the fiscal period. Consider maturity, interest cost, and the company’s ability to generate cash.'
  if (lower.includes('cash')) return 'A reported cash balance or cash movement. Read the statement label and period; cash flow is different from accounting profit.'
  if (lower.includes('income') || lower.includes('profit') || lower.includes('earn')) return 'An accounting earnings figure for the displayed period. Check the statement notes and compare multiple periods.'
  return `Reported financial statement line item: ${label}. Values and labels are supplied by the data source and can vary by company and accounting period.`
}

function formatFinancial(value, label, currency) {
  if (value == null || !Number.isFinite(Number(value))) return '—'
  const lower = label.toLowerCase()
  if (lower.includes('margin') || lower.includes('tax rate') || lower.includes('growth')) return `${(Number(value) * 100).toFixed(1)}%`
  if (lower.includes('per share') || lower.includes('eps') || lower.includes('dividend')) return formatPrice(value, currency)
  if (lower.includes('share')) return formatNumber(value)
  return formatCompact(value, currency)
}

